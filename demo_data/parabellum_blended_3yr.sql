--    correlation + noise), and blended in the real receipt data
--    at its actual observed months. The provenance CSV lists
--    every row's origin.'
--
-- The provenance manifest is at:
--     demo_data/parabellum_blended_3yr_provenance.csv
--
-- Synthetic generation model (fully documented in the script
-- demo_data/README.md):
--   demand(t) = base * seasonal(t) * weather_factor(t) * trend(t)
--             + serial_corr * previous_demand + noise
--   where:
--     seasonal(t)      = peaks Feb (dry season), troughs Aug (wet)
--     weather_factor   = per-material sensitivity to wet-season rainfall
--     trend(t)         = per-material annual growth (2-4%)
--     serial_corr      = 0.35 (this month partly explained by last)
--     noise            = per-material +/- 20-35%
--
-- =============================================================
